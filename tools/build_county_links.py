"""Build data/county_links.json: each county's official school board and tax collector websites.

    python tools/build_county_links.py

Sources: the Florida School Boards Association's list of member districts (each links to its board page) and the
Florida Tax Collectors Association's "Your Tax Collector" page (each county links to its tax collector). The
site uses these to point visitors to the right office when the directory doesn't list its people yet.
"""
import json
import re
import sys
from pathlib import Path

from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from collector.geo import FLORIDA_COUNTIES, canonical_county  # noqa: E402
from collector.scrapers.base import PoliteHttpClient  # noqa: E402
from collector.scrapers.registry import user_agent  # noqa: E402

SOURCES = {
    "school_board": ("https://fsba.org/membership/school-boards/", "Florida School Boards Association: Florida School Boards"),
    "tax_collector": ("https://floridataxcollectors.com/your-tax-collector/", "Florida Tax Collectors Association: Your Tax Collector"),
}


def county_links(html: str) -> dict[str, str]:
    out = {}
    for a in BeautifulSoup(html, "lxml").select("a[href^='http']"):
        text = " ".join(a.get_text(" ").split())
        name = re.sub(r"\s*(County|School|District|Board|Public|Schools).*$", "", text, flags=re.I).strip()
        name = {"Saint Johns": "St. Johns", "Saint Lucie": "St. Lucie"}.get(name.title() if name.isupper() else name, name)
        county = canonical_county(name)
        if county and county not in out:
            out[county] = a["href"]
    return out


def main() -> None:
    client = PoliteHttpClient(user_agent(), 2, 30, 1)
    result = {"_how_to": "Generated by tools/build_county_links.py. Official sites for offices the directory may not list yet.",
              "sources": {k: {"name": name, "url": url} for k, (url, name) in SOURCES.items()}, "counties": {}}
    for key, (url, _name) in SOURCES.items():
        for county, link in county_links(client.get(url)).items():
            result["counties"].setdefault(county, {})[key] = link
    result["counties"] = dict(sorted(result["counties"].items()))
    missing = {k: [c for c in FLORIDA_COUNTIES if k not in result["counties"].get(c, {})] for k in SOURCES}
    (ROOT / "data" / "county_links.json").write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote links for {len(result['counties'])} counties; missing: {missing}")


if __name__ == "__main__":
    main()
