"""Stand-in mayors and official websites for every Florida municipality, from Wikipedia article pages.

    python tools/wikipedia_mayors.py        # writes data/wikipedia_mayors.json (takes ~10 minutes)

Reads Wikipedia's "List of municipalities in Florida" (all 411, with their counties), then each city's article,
taking two lines from its infobox: "Mayor" and "Website". Only ordinary article pages are read, through the same
polite client the collector uses (robots.txt respected; the Wikipedia API and Wikidata query service are disallowed
for automated clients and are not used).

How the site uses this file:
- Website: a starting point for tools/find_council_pages.py, so the city's own council page can be found.
- Mayor: shown only for cities with no official source, labelled "From Wikipedia, not confirmed by the city", and
  dropped as soon as the city's own page is collected. In a check against 34 cities whose own sites name the
  mayor, Wikipedia agreed for 31.
"""
import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from bs4 import BeautifulSoup

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from collector.scrapers.base import FetchError, HostSchedule, PoliteHttpClient  # noqa: E402
from collector.scrapers.registry import user_agent  # noqa: E402

OUT = ROOT / "data" / "wikipedia_mayors.json"
LIST = "https://en.wikipedia.org/wiki/List_of_municipalities_in_Florida"
SCHEDULE = HostSchedule()
NAME = re.compile(r"[A-Z][A-Za-z.'’\- ]{3,60}")


def client() -> PoliteHttpClient:
    return PoliteHttpClient(user_agent(), 1, 30, 1, schedule=SCHEDULE)


def municipalities(html: str) -> list[dict]:
    """(name, county, article) for each row of the municipality table."""
    out = []
    for table in BeautifulSoup(html, "lxml").select("table.wikitable"):
        for tr in table.select("tr"):
            cells = tr.select("td")
            if len(cells) < 2:
                continue
            place, county = cells[0].select_one("a[href]"), cells[1].get_text(" ", strip=True)
            if place and "/wiki/" in place["href"]:
                out.append({"municipality": place.get_text(" ", strip=True), "county": county,
                            "article": requests_url(place["href"])})
    return list({m["municipality"]: m for m in out}.values())


def requests_url(href: str) -> str:
    return href if href.startswith("http") else "https://en.wikipedia.org" + href


def infobox(html: str) -> dict:
    """The infobox's mayor (if a mayor line exists) and official website."""
    result = {"name": None, "website": None}
    for tr in BeautifulSoup(html, "lxml").select("table.infobox tr"):
        th, td = tr.select_one("th"), tr.select_one("td")
        if not th or not td:
            continue
        label = th.get_text(" ", strip=True).lstrip("• ").strip()
        if re.fullmatch(r"(?i)mayor", label) and not result["name"]:
            for sup in td.select("sup"):
                sup.decompose()
            text = re.sub(r"\(.*?\)", "", td.get_text(" ", strip=True))
            text = " ".join(text.split()).strip(" ,;")
            if NAME.fullmatch(text):
                result["name"] = text
        elif label.lower() == "website" and (a := td.select_one("a.external[href]")):
            result["website"] = a["href"]
    return result


def read(place: dict) -> dict:
    try:
        return {**place, **infobox(client().get(place["article"]))}
    except FetchError as exc:
        return {**place, "error": str(exc)[:120]}


def main() -> None:
    places = municipalities(client().get(LIST))
    print(f"{len(places)} municipalities", file=sys.stderr)
    with ThreadPoolExecutor(max_workers=2) as pool:
        rows = list(pool.map(read, places))
    OUT.write_text(json.dumps({"_how_to": "Generated by tools/wikipedia_mayors.py from Wikipedia article infoboxes. "
                                          "Mayors here are unconfirmed stand-ins; see the tool's docstring.",
                               "source": LIST, "municipalities": rows}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} municipalities ({sum(1 for r in rows if r.get('name'))} with a mayor, "
          f"{sum(1 for r in rows if r.get('website'))} with a website) to {OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
